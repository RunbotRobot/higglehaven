-- #2370 (sub-issue of #2368, following up on #2012/#2013's precedent for
-- water): gives the Worker a way to actually read the real-world biome
-- classification scripts/ingest-geo-data.mjs can now also produce (#2370
-- extended that same script to derive a coarse biome -- near_water/
-- lowland/upland/alpine -- per sampled grid point, alongside its existing
-- water-cell output). Cloudflare Workers have no filesystem at request
-- time, so exactly as geo_water_cells (migrations/0128) was the missing
-- piece for water, this table is the missing piece for biome.
--
-- Dense, unlike geo_water_cells' sparse "water cells only" format: biome
-- has no single safe default to omit from the way "not a water cell"
-- obviously means buildable -- every successfully-classified sampled
-- point needs its own row, and a point with no nearby row is genuinely
-- unclassified (biome stays NULL, #2369's own column default), not
-- defaulted to one of these bands. spacing_m is carried on every row for
-- the same reason geo_water_cells carries it: a consumer needs it
-- alongside the coordinates to decide how close counts as "this cell's
-- own data," and this dataset is small enough (at most a few hundred
-- rows for any radius this world will need for a long while) that
-- denormalizing costs nothing real.
CREATE TABLE geo_biome_cells (
  x_m REAL NOT NULL,
  y_m REAL NOT NULL,
  biome TEXT NOT NULL,
  spacing_m REAL NOT NULL,
  generated_at TEXT NOT NULL,
  PRIMARY KEY (x_m, y_m)
);

