-- #2850 (leaf of #2373, sub-issue of #2368, Option C real terrain --
-- owner decision 2026-10-27): geo_biome_cells (migrations/0149) already
-- stores one row per sampled grid point, but scripts/ingest-geo-data.mjs
-- only ever persisted the *derived* biome bucket -- the real elevationM
-- it fetches from USGS EPQS to compute that bucket was discarded
-- immediately after. That fetch is the expensive part (a live,
-- rate-limited network call per point); the biome classification itself
-- is free once elevationM is known. Adding a sibling column rather than
-- a parallel table, since every biome cell already corresponds to
-- exactly one sampled point with its own elevation reading available at
-- ingest time -- a parallel geo_elevation_cells table would just
-- duplicate the same (x_m, y_m) primary key for no benefit.
--
-- Nullable: existing rows (and the real seed data below) may or may not
-- have a known elevation -- #2369's own biome column precedent, and
-- this column's own elevationAt() reader (worker/lib/world-generation.js),
-- both treat "no row, or a row with elevation_m IS NULL" as genuinely
-- unclassified, never defaulted to sea level.
