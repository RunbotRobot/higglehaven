export function countryName(code, locale = undefined) {
  try {
    return new Intl.DisplayNames(locale, { type: 'region' }).of(code) || code;
  } catch {
    return code;
  }
}

// [{ code, name }] sorted by name, United States first only because the form's default is chosen elsewhere.
export function shippingCountryOptions(locale = undefined) {
  return SHIPPING_COUNTRY_CODES.map((code) => ({ code, name: countryName(code, locale) }))
    .sort((a, b) => a.name.localeCompare(b.name, locale));
}
