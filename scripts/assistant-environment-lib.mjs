// #3458 (part of #3444): what it takes to start an assistant session that has no
// repository. The three programs (assistant-lib/shift/reply.mjs) are fetched
// into a fixed directory at a pinned commit and checked against checksums, and
// the session is started with permission mode `default` and only the exact shift
// commands pre-approved. This file builds both texts; nothing here touches the
// network or the filesystem, so it runs in the plain test pool. The command-line
// wrapper is scripts/assistant-environment.mjs; the maintainer's guide is
// docs/assistant-environment.md.
import { ASSISTANT_LOGIN_PATTERN } from './assistant-lib.mjs';

export const PROGRAM_FILES = ['assistant-lib.mjs', 'assistant-shift.mjs', 'assistant-reply.mjs'];
export const INSTALL_DIR = '/opt/assistant';
export const DEFAULT_REPO = 'RunbotRobot/higglehaven';
// The one extra host the environment's network must allow: public file content.
export const PROGRAMS_HOST = 'raw.githubusercontent.com';
// What assistant-reply.mjs accepts as its first word.
export const REPLY_ACTIONS = ['reply', 'end', 'escalate', 'answer-question', 'escalate-question'];

const SHA256 = /^[0-9a-f]{64}$/;
const COMMIT = /^[0-9a-f]{40}$/;
const REPO = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;

// files: { 'assistant-lib.mjs': '<sha256 hex>', ... } for every PROGRAM_FILES.
// The result is a bash script (under 100 lines, idempotent, never needs a
// secret) for the environment's setup-script field. It fails closed: a missing
// file, a download error or a checksum that does not match stops it before
// anything is installed, and a script that fails stops the session starting.
export function buildSetupScript({ commit, files, repo = DEFAULT_REPO }) {
  if (!COMMIT.test(commit || '')) throw new Error('commit must be a full 40-character commit id');
  if (!REPO.test(repo)) throw new Error(`"${repo}" is not an owner/name repository`);
  for (const name of PROGRAM_FILES) {
    if (!SHA256.test(files?.[name] || '')) throw new Error(`missing or malformed sha256 for ${name}`);
  }
  const sums = PROGRAM_FILES.map((name) => `${files[name]}  ${name}`).join('\n');
  return `#!/usr/bin/env bash
# Generated by scripts/assistant-environment.mjs for ${repo} at ${commit}.
# Installs the assistant's three programs, checked against the checksums below.
set -euo pipefail
COMMIT=${commit}
BASE="\${ASSISTANT_PROGRAMS_BASE:-https://${PROGRAMS_HOST}/${repo}/\$COMMIT/scripts}"
DIR="\${ASSISTANT_DIR:-${INSTALL_DIR}}"
SUMS='${sums}'
verify() { (cd "\$1" && printf '%s\\n' "\$SUMS" | sha256sum --check --status --strict); }
if [ -f "\$DIR/.commit" ] && [ "\$(cat "\$DIR/.commit")" = "\$COMMIT" ] && verify "\$DIR"; then
  echo "assistant programs already at \$COMMIT"
  exit 0
fi
TMP="\$(mktemp -d)"
trap 'rm -rf "\$TMP"' EXIT
for f in ${PROGRAM_FILES.join(' ')}; do
  curl --fail --silent --show-error --max-time 30 --retry 2 "\$BASE/\$f" --output "\$TMP/\$f"
done
verify "\$TMP" || { echo "assistant programs: checksum mismatch, nothing installed" >&2; exit 1; }
printf '%s\\n' "\$COMMIT" > "\$TMP/.commit"
chmod 755 "\$TMP"
chmod 444 "\$TMP"/*.mjs "\$TMP/.commit"
chmod 555 "\$TMP"
rm -rf "\$DIR"
mkdir -p "\$(dirname "\$DIR")"
mv "\$TMP" "\$DIR"
trap - EXIT
echo "assistant programs installed at \$COMMIT"
`;
}

// The permission rules for one assistant, as the settings object the session is
// started with. Mode `default` makes every other tool call wait for a human who
// is not there; only these exact program invocations are pre-approved. The
// program path and the assistant's name are fixed in each rule.
export function permissionRules(name) {
  const login = String(name || '').trim().toLowerCase();
  const short = login.replace(/^assistant-/, '');
  if (!ASSISTANT_LOGIN_PATTERN.test(`assistant-${short}`)) throw new Error(`"${name}" is not an assistant name (use a name like juniper)`);
  const base = `node ${INSTALL_DIR}/assistant-reply.mjs --name ${short}`;
  return {
    permissions: {
      defaultMode: 'default',
      allow: [
        `Bash(node ${INSTALL_DIR}/assistant-shift.mjs --name ${short})`,
        ...REPLY_ACTIONS.map((action) => `Bash(${base} ${action}:*)`),
      ],
    },
  };
}
